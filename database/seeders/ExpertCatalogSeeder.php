class ExpertCatalogSeeder extends Seeder
{
    public function run(): void
    {
        $vat = TaxClass::firstOrCreate(
            ['code' => 'VAT_STD'],
            ['name' => 'قياسي 14%', 'rate' => 0.14, 'is_inclusive' => true, 'is_default' => true]
        );

        $warehouse = Warehouse::firstOrCreate(
            ['code' => 'MAIN'],
            ['name' => 'المخزن الرئيسي', 'type' => 'store', 'is_default' => true, 'is_active' => true]
        );

        $categories = $this->seedCategories();
        $products   = $this->catalog();
        $costRatio  = 0.70;
        $created    = 0;

        foreach ($products as $idx => $row) {
            [$name, $catName, $sell, $priceEgp, $short, $long, $unitLabel] = $row;
            $isWeighted = $sell === 'weight';
            $skuRoot    = 'EXP-' . str_pad((string) ($idx + 1), 4, '0', STR_PAD_LEFT);

            $product = Product::updateOrCreate(
                ['sku_root' => $skuRoot],
                [
                    'category_id'       => $categories[$catName]->id,
                    'tax_class_id'      => $vat->id,
                    'name'              => $name,
                    'slug'              => Str::slug($name, '-', 'ar') . '-' . ($idx + 1),
                    'type'              => $isWeighted ? ProductType::Weighted : ProductType::Simple,
                    'short_description' => $short,
                    'long_description'  => $long,
                    'status'            => ProductStatus::Active,
                    'has_variants'      => false,
                    'is_featured'       => $idx < 8,
                    'sort_order'        => $idx,
                ]
            );

            $variant = ProductVariant::updateOrCreate(
                ['sku' => $skuRoot . '-D'],
                [
                    'product_id'   => $product->id,
                    'barcode'      => '623' . str_pad((string) (200000 + $idx), 10, '0', STR_PAD_LEFT),
                    'price_minor'  => (int) round($priceEgp * 100),
                    'cost_minor'   => (int) round($priceEgp * $costRatio * 100),
                    'unit'         => $isWeighted ? UnitOfMeasure::Gram : UnitOfMeasure::Piece,
                    'step'         => '1.000',
                    'unit_label'   => $unitLabel,
                    'weight_grams' => $isWeighted ? null : null,
                    'is_default'   => true,
                    'is_active'    => true,
                ]
            );

            // الكمية صفر كما طُلب
            StockLevel::updateOrCreate(
                ['variant_id' => $variant->id, 'warehouse_id' => $warehouse->id],
                [
                    'on_hand'          => 0,
                    'reserved'         => 0,
                    'reorder_point'    => $isWeighted ? 1000 : 5,
                    'reorder_qty'      => $isWeighted ? 10000 : 20,
                    'last_movement_at' => now(),
                ]
            );

            $created++;
        }

        $this->command?->info("ExpertCatalogSeeder: {$created} منتجًا في " . count($categories) . ' تصنيفات — المخزون = 0.');
    }

    /** @return array<string, Category> */
    private function seedCategories(): array
    {
        $defs = [
            'المشروبات'         => 'heroicon-o-beaker',
            'البهارات والتوابل' => 'heroicon-o-fire',
            'دقيق ونشا'         => 'heroicon-o-rectangle-stack',
            'مشروبات ساخنة'     => 'heroicon-o-building-storefront',
            'بقدونس وكرفس'      => 'heroicon-o-sparkles',
            'معلبات'            => 'heroicon-o-archive-box',
            'مستلزمات حلويات'   => 'heroicon-o-cake',
            'بذور صحية'         => 'heroicon-o-shopping-bag',
        ];

        $out = [];
        $i   = 0;
        foreach ($defs as $name => $icon) {
            $out[$name] = Category::updateOrCreate(
                ['slug' => Str::slug($name, '-', 'ar')],
                [
                    'name'        => $name,
                    'icon'        => $icon,
                    'sort_order'  => $i++,
                    'is_active'   => true,
                    'is_featured' => true,
                ]
            );
        }

        return $out;
    }

