/**
 * سيدر كتالوج خبير — تصنيفات ومنتجات عبد القادر العطّار كاملة.
 * الكمية الافتتاحية = صفر لكل المنتجات (تُحدَّث لاحقًا من المخزون).
 *
 * التشغيل:
 *   php artisan db:seed --class=ExpertCatalogSeeder
